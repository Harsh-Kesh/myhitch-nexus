/** The mock "today". Every seed date is relative to this so the fixtures never
 *  drift into looking stale, and so server/client renders always agree. */
export const NOW = new Date("2026-08-12T10:00:00.000Z");

export function daysAgo(days: number): string {
  return new Date(NOW.getTime() - days * 86_400_000).toISOString();
}

export function daysAhead(days: number): string {
  return new Date(NOW.getTime() + days * 86_400_000).toISOString();
}

export function hoursAhead(hours: number): string {
  return new Date(NOW.getTime() + hours * 3_600_000).toISOString();
}

export function hoursAgo(hours: number): string {
  return new Date(NOW.getTime() - hours * 3_600_000).toISOString();
}

