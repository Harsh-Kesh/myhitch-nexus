function sub(
  languageCode: string,
  language: string,
  kind: SubtitleTrack["kind"] = "subtitles",
  autoGenerated = false,
): SubtitleTrack {
  return {
    id: `sub_${languageCode}_${kind}`,
    language,
    languageCode,
    kind,
    autoGenerated,
    status: "ready",
  };
}

function audio(
  languageCode: string,
  language: string,
  kind: AudioTrack["kind"] = "original",
): AudioTrack {
  return { id: `aud_${languageCode}_${kind}`, language, languageCode, kind };
}

